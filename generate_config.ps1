$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()

function Get-RandomByte {
    $buf = [byte[]]::new(1)
    $rng.GetBytes($buf)
    return $buf[0]
}

function Get-RandomUInt32 {
    $buf = [byte[]]::new(4)
    $rng.GetBytes($buf)
    return [BitConverter]::ToUInt32($buf, 0)
}


$keyMask = Get-RandomByte
if ($keyMask -eq 0) { $keyMask = 0x5A }


$strMask = Get-RandomByte
if ($strMask -eq 0) { $strMask = 0x3C }


